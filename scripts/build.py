"""Render maintained Markdown using the vendored Claude-style md2html template."""
from pathlib import Path
from html import escape
import json,re,shutil,hashlib
from markdown_it import MarkdownIt
from bs4 import BeautifulSoup
ROOT=Path(__file__).resolve().parents[1]; DIST=ROOT/'dist'; SITE=DIST/'site'
SITE.mkdir(parents=True,exist_ok=True)
(SITE/'.nojekyll').touch()
book=json.loads((ROOT/'book.json').read_text()); chapters=book['chapters']
parser=MarkdownIt('commonmark',{'html':True,'breaks':False}).enable('table')
template=(ROOT/'vendor/md2html/template.html').read_text()
template=re.sub(r'\s*<link[^>]*>', '',template)
template=re.sub(r'<script src="[^"]*mermaid[^>]*></script>','',template)
template=re.sub(r'    // ---------- Mermaid ----------.*?    function toggleTheme\(\)', '    function toggleTheme()',template,flags=re.S)
template=template.replace('if (!links.length) {', 'if (!links.length && !document.querySelector("#toc-nav a")) {').replace('      renderMermaid();','').replace('Permalink','章节链接').replace('Copy code','复制代码')
template=template.replace('    const saved = localStorage.getItem(STORAGE_KEY);','    let saved; try { saved = localStorage.getItem(STORAGE_KEY); } catch {}')
template=template.replace('      localStorage.setItem(STORAGE_KEY, next);','      try { localStorage.setItem(STORAGE_KEY, next); } catch {}')
template=template.replace('</style>',(ROOT/'theme/handbook.css').read_text()+'\n</style>')
template=template.replace('Generated by <a href="#">md2html</a>','主题基于 <a href="https://github.com/haidang1810/md2html">md2html</a>')

def render_markdown(chapter):
    text=(ROOT/'chapters'/f"{chapter['slug']}.md").read_text()
    soup=BeautifulSoup(parser.render(text),'html.parser')
    title=soup.h1; title.decompose()
    for index,h in enumerate(soup.find_all(['h2','h3']),1):
        match=re.match(r'(\d+\.\d+)',h.get_text())
        h['id']=chapter['slug']+'-'+(match.group(1).replace('.','-') if match else str(index))
    for img in list(soup.find_all('img')):
        img['src']=img['src'].replace('../assets/','assets/')
        img['loading']='lazy'
        if '/covers/' in img['src']:img['class']='chapter-cover'
        parent=img.parent
        figure=soup.new_tag('figure'); parent.replace_with(figure); figure.append(img.extract())
        if '/diagrams/' in img['src']:
            figure['class']='mechanism'; cap=soup.new_tag('figcaption');cap.string=img['alt'];figure.append(cap)
            link=soup.new_tag('a',href=img['src'].replace('.svg','.html'));link['class']='diagram-link';link.string='打开完整机制图';figure.append(link)
    for table in list(soup.find_all('table')):
        headers=[h.get_text() for h in table.select('thead th')]; rows=table.select('tbody tr')
        if len(headers)>=5 or any(len(row.get_text())>300 for row in rows):
            replacement=soup.new_tag('div')
            for row in rows:
                cells=row.find_all('td'); section=soup.new_tag('section');section['class']='record'
                main_index=1 if headers[0]=='序号' else 0
                term_label=soup.new_tag('p');term_label['class']='record-kind';term_label.string=headers[main_index];section.append(term_label)
                heading=soup.new_tag('h3');heading.append(BeautifulSoup(cells[main_index].decode_contents(),'html.parser'));section.append(heading)
                dl=soup.new_tag('dl')
                for index,cell in enumerate(cells):
                    if index==main_index:continue
                    term=soup.new_tag('dt');term.string=headers[index];dl.append(term)
                    definition=soup.new_tag('dd');definition.append(BeautifulSoup(cell.decode_contents(),'html.parser'));dl.append(definition)
                section.append(dl);replacement.append(section)
            table.replace_with(replacement)
        else:
            wrap=soup.new_tag('div');wrap['class']='table-wrap';table.wrap(wrap)
    return str(soup)

rendered={chapter['slug']:render_markdown(chapter) for chapter in chapters}
def toc_for(chapter=None,body=''):
    nav='<a class="lvl-2" href="index.html">手册首页 / PDF 下载</a>'
    for c in chapters:
        nav+=f'<a class="lvl-2" href="{c["slug"]}.html">{escape(c["title"])}</a>'
        if c==chapter:
            soup=BeautifulSoup(body,'html.parser')
            for h in soup.find_all(['h2','h3'],id=True):nav+=f'<a class="lvl-3" href="#{h["id"]}">{escape(h.get_text())}</a>'
    return nav

def page(title,subtitle,body,nav,source='chapters/*.md'):
    values={'LANG':'zh','REC_LABEL':'推荐','TITLE':title,'SUBTITLE':subtitle,'DOC_TYPE':'HANDBOOK','SOURCE_FILE':source,'DATE':book['date'],'READ_TIME':'按章节阅读','BRAND_LABEL':'FDU 交付手册','TOC_TITLE':'章节目录','PRINT_TOOLTIP':'打印 / 保存 PDF','THEME_TOOLTIP':'切换主题','CLOSE_LABEL':'关闭','SKIP_LINK_LABEL':'跳到正文','FOOTER_NOTE':'从 FDE 到 FDU · 2026 年 10 月整理版'}
    result=template
    for key,value in values.items():result=result.replace('{{'+key+'}}',escape(value))
    result=result.replace('<!-- TOC_ENTRIES -->',nav)
    result=re.sub(r'<!-- CONTENT_START -->.*?<!-- CONTENT_END -->',lambda m:'<!-- CONTENT_START -->'+body+'<!-- CONTENT_END -->',result,flags=re.S)
    assert not re.search(r'\{\{[A-Z_]+\}\}',result)
    return result

for index,chapter in enumerate(chapters):
    body=rendered[chapter['slug']]
    links=[]
    for offset,label in [(-1,'上一章'),(1,'下一章')]:
        target=index+offset
        if 0<=target<len(chapters):links.append(f'<a href="{chapters[target]["slug"]}.html">{label}：{escape(chapters[target]["title"])}</a>')
    body+='<nav class="chapter-nav" aria-label="章节翻页">'+''.join(links)+'</nav>'
    (SITE/f'{chapter["slug"]}.html').write_text(page(chapter['title'],'从 FDE 到 FDU：重新定义 AI 交付',body,toc_for(chapter,body),f'chapters/{chapter["slug"]}.md'))
intro='''<section class="book-intro"><img src="assets/covers/book.png" alt="从 FDE 到 FDU：重新定义 AI 交付，整书封面"><div><h2 id="read">从交付瓶颈，读到运行机制</h2><p>序言、八章正文与一份补充材料。按顺序阅读，也可直接进入工程机制、全球案例或中国落地章节。</p><div class="download-actions"><a href="00-guide.html">开始阅读</a><a href="downloads/fdu-handbook.pdf" download>下载 PDF 电子书</a></div><p>2026 年 10 月整理版 · 全文、图解与封面可离线阅读</p></div></section><h2 id="chapters">章节</h2><div class="chapter-grid">'''
for c in chapters[1:9]:
    intro+=f'<article class="chapter-card"><a href="{c["slug"]}.html"><img src="assets/covers/{c["slug"][:2]}.png" alt="{escape(c["title"])}"><h3>{escape(c["title"])}</h3></a><p>约 {round(c["characters"]/600)} 分钟 · 阅读本章</p></article>'
intro+='</div><p><a href="09-supplement.html">补充阅读：生产级系统的生成与治理</a></p>'
(SITE/'index.html').write_text(page(book['title'],'企业级 AI 交付：组织、工程、治理与商业结果',intro,toc_for()))
body='<section class="cover-page"><img src="assets/covers/book.png" alt="整书封面"></section><section class="print-toc"><h1>目录</h1><p>从 FDE 到 FDU：重新定义 AI 交付</p><ol>'
for c in chapters:body+=f'<li><a href="#book-{c["slug"]}">{escape(c["title"])}</a></li>'
body+='</ol><p>2026 年 10 月整理版</p></section>'
for c in chapters:body+=f'<section class="book-chapter" id="book-{c["slug"]}"><h1>{escape(c["title"])}</h1>{rendered[c["slug"]]}</section>'
(SITE/'book.html').write_text(page(book['title'],'完整电子书打印稿',body,toc_for()))
shutil.copytree(ROOT/'assets',SITE/'assets',dirs_exist_ok=True)
(SITE/'downloads').mkdir(exist_ok=True)
(ROOT/'dist/build-manifest.json').write_text(json.dumps({'pages':len(chapters)+2,'chapters':len(chapters),'covers':9,'diagrams':6,'manuscript_sha256':hashlib.sha256((ROOT/'source/完整原稿.md').read_bytes()).hexdigest(),'renderer':'haidang1810/md2html + deterministic Markdown renderer'},ensure_ascii=False,indent=2)+'\n')
print(f'Built {len(chapters)+2} pages at {SITE}')
